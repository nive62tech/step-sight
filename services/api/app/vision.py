"""Compact provider predictions, bound locally to the exact submitted image.

Transport IDs never need to be generated by a language model. A fresh call owns
its observation; local binding preserves that association across asynchronous
responses. This does not grant permission or confirm a visual result.
"""
from typing import Annotated, Literal
from uuid import uuid4

from pydantic import Field, model_validator

from app.contracts import (
    Action,
    ActionProposal,
    Bounds,
    Contract,
    Evidence,
    GuidanceStep,
    Observation,
    Postcondition,
    ProviderResult,
    Target,
    TargetLocation,
    VerificationResult,
    VerificationStatus,
)

Detail = Annotated[str, Field(min_length=1, max_length=500)]


class VisualTarget(Contract):
    bounds: Bounds
    visible_label: str = Field(max_length=200, description="Exact visible control text, without adding its role or a paraphrase; use a short visual description only for unlabeled icons.")


class VisualStep(Contract):
    instruction: str = Field(min_length=1, max_length=1000)
    explanation: str = Field(max_length=1500)
    target: VisualTarget | None = None
    expected_user_action: Literal["click", "type", "scroll", "key_chord", "manual", "wait"]
    postconditions: list[Postcondition] = Field(min_length=1, max_length=5)
    evidence: list[Detail] = Field(min_length=1, max_length=5)
    uncertainty: list[Detail] = Field(default_factory=list, max_length=5)


class VisualVerification(Contract):
    status: VerificationStatus
    evidence: list[Detail] = Field(min_length=1, max_length=5)
    unmet_postconditions: list[Detail] = Field(default_factory=list, max_length=5)
    recovery_suggestion: str | None = Field(default=None, max_length=1000)

    @model_validator(mode="after")
    def positive_confirmation(self):
        if self.status == VerificationStatus.CONFIRMED and self.unmet_postconditions:
            raise ValueError("confirmation cannot have unmet postconditions")
        return self


class VisualAction(Contract):
    action: Action
    effect: str = Field(min_length=1, max_length=500)
    risk: Literal["low", "manual"]
    provider_confirmation_required: bool = False


class VisualResult(Contract):
    step: VisualStep | None = None
    verification: VisualVerification | None = None
    action_proposal: VisualAction | None = None
    completed: bool = False

    def bind(self, observation: Observation, *, has_previous: bool) -> ProviderResult:
        def evidence(details):
            return [Evidence(observation_id=observation.id, detail=detail) for detail in details]

        verification = VerificationResult(**self.verification.model_dump(exclude={"evidence"}),
            evidence=evidence(self.verification.evidence), provenance="gemini") if self.verification else None
        confirmed = verification is not None and verification.status == VerificationStatus.CONFIRMED
        if has_previous and not verification:
            raise ValueError("previous step needs visual verification")
        # Apply the existing no-advance rule before constructing any next step.
        if has_previous and not confirmed:
            return ProviderResult(step=None, verification=verification, action_proposal=None, completed=False)
        if self.completed and (not has_previous or not confirmed):
            raise ValueError("completion requires verified previous-step evidence")
        step = None
        if self.step:
            step = GuidanceStep(id=uuid4(), source_observation_id=observation.id,
                **self.step.model_dump(exclude={"evidence", "target"}), evidence=evidence(self.step.evidence),
                target=Target(geometry_id=observation.geometry_id, **self.step.target.model_dump()) if self.step.target else None)
        proposal = ActionProposal(id=uuid4(), source_observation_id=observation.id, geometry_id=observation.geometry_id,
            **self.action_proposal.model_dump()) if self.action_proposal else None
        return ProviderResult(step=step, verification=verification, action_proposal=proposal, completed=self.completed)


class VisualLocation(Contract):
    target: VisualTarget | None = None
    evidence: list[Detail] = Field(min_length=1, max_length=5)
    uncertainty: list[Detail] = Field(default_factory=list, max_length=5)

    def bind(self, observation: Observation) -> TargetLocation:
        return TargetLocation(source_observation_id=observation.id,
            target=Target(geometry_id=observation.geometry_id, **self.target.model_dump()) if self.target else None,
            evidence=[Evidence(observation_id=observation.id, detail=detail) for detail in self.evidence],
            uncertainty=self.uncertainty)
